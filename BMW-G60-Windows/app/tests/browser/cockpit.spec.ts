import {test,expect} from '@playwright/test';

test('offline evidence inspection, saved replay, editing, approval, and frozen deck export',async({page,request},testInfo)=>{
 const health=await (await request.get('/api/v1/health')).json();
 expect(health.rehearsal,'Start against a disposable rehearsal database with BMWPM_REHEARSAL=1.').toBe(true);
 // Deny every non-loopback browser request for the entire rehearsal.
 const externalRequests:string[]=[];
 await page.route('**/*',route=>{const u=new URL(route.request().url());if(['127.0.0.1','localhost'].includes(u.hostname))return route.continue();externalRequests.push(u.origin);return route.abort();});
 let webConnected=false;
 await page.route('**/api/v1/connectors/web',async route=>{
  const payload=route.request().postDataJSON() as {urls:string[]};
  expect(payload.urls).toContain('https://example.com/forum/g60-touchscreen');
  webConnected=true;
  await route.fulfill({json:{id:'web-e2e',kind:'web_connector',state:'succeeded',input:payload,result:{imported:[{url:payload.urls[0],records:1}],skipped:[],failed:[]},error:null,progress:'Complete',created_at:new Date().toISOString(),updated_at:new Date().toISOString()}});
 });
 await page.goto('/');
 await expect(page.getByText('3,610',{exact:true}).first()).toBeVisible();
 await page.getByRole('button',{name:'Connect web evidence',exact:true}).click();
 const connector=page.getByRole('dialog',{name:'Connect web evidence',exact:true});
 await connector.getByLabel('Seed URLs').fill('https://example.com/forum/g60-touchscreen');
 await connector.getByLabel('Model').selectOption('G60');
 await connector.getByLabel('Market').fill('US');
 await connector.getByLabel('Powertrain').selectOption('unknown');
 await connector.getByLabel('Source label').fill('Mock owner forum');
 await connector.getByRole('button',{name:'Connect evidence',exact:true}).click();
 await expect(page.getByText('Web evidence connected.',{exact:true})).toBeVisible();
 expect(webConnected).toBe(true);
 await page.getByRole('button',{name:'Requirements',exact:true}).click();
 await page.getByLabel('Search requirements').fill('Touch screen, operation');
 await page.getByRole('button',{name:'Touch screen, operation',exact:true}).click();
 const drawer=page.getByRole('dialog',{name:'Requirement review',exact:true});
 await expect(drawer.getByText('3,610 records',{exact:false}).first()).toBeVisible();
 await drawer.getByRole('button',{name:'View original row'}).first().click();
 const evidence=page.getByRole('dialog',{name:'Original evidence',exact:true});
 await expect(evidence.getByText('Feedback_Explorer',{exact:false}).first()).toBeVisible();
 await expect(evidence.getByRole('link',{name:'Open original file'})).toHaveAttribute('href',/\/sources\/.+\/file/);
 await evidence.getByRole('button',{name:'Close dialog',exact:true}).click();
 await drawer.getByRole('button',{name:'Replay analysis',exact:true}).click();
 await expect(drawer.getByText('Saved AI interpretation',{exact:true})).toBeVisible({timeout:30000});
 await expect(drawer.getByText('gpt-4.1-mini-2025-04-14',{exact:false})).toBeVisible();
 await drawer.getByRole('button',{name:'Edit',exact:true}).click();
 const edit=page.getByRole('dialog',{name:'Edit requirement',exact:true});
 await edit.getByLabel('Title',{exact:true}).fill('Make common touchscreen tasks easy to find');
 await edit.getByLabel('Decision rationale').fill('Automated offline rehearsal: clarify the need; verify affected variants with customers.');
 await edit.getByRole('button',{name:'Record decision',exact:true}).click();
 await expect(drawer.getByRole('heading',{name:'Make common touchscreen tasks easy to find'})).toBeVisible();
 await expect(drawer.getByText('Revision 2',{exact:true})).toBeVisible();
 await drawer.getByRole('button',{name:'Approve',exact:true}).click();
 const approve=page.getByRole('dialog',{name:'Approve requirement',exact:true});
 await approve.getByLabel('PM impact band').selectOption('High');
 await approve.getByLabel('Decision rationale').fill('Automated rehearsal approval only: interaction affects frequently used controls. Human PM validation remains required.');
 await approve.getByRole('button',{name:'Record decision',exact:true}).click();
 await expect(drawer.getByText('approved',{exact:true})).toBeVisible();
 await drawer.getByRole('button',{name:'Close dialog',exact:true}).click();
 await page.getByRole('button',{name:'Decisions & audit',exact:true}).click();
 await expect(page.getByText('Audit chain verified',{exact:true})).toBeVisible();
 const downloadEvent=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export board deck',exact:true}).click();
 const download=await downloadEvent;
 const deckPath=testInfo.outputPath('offline-rehearsal.pptx');await download.saveAs(deckPath);
 expect(download.suggestedFilename()).toMatch(/\.pptx$/);
 await page.screenshot({path:testInfo.outputPath('decisions.png'),fullPage:true});
 const exports=await (await request.get('/api/v1/exports')).json();
 const snapshot=await (await request.get(`/api/v1/exports/${exports[0].id}/snapshot`)).json();
 expect(snapshot.approved).toHaveLength(1);
 expect(snapshot.approved[0].title).toBe('Make common touchscreen tasks easy to find');
 expect(snapshot.approved[0].denominator).toBe(3610);
 expect(snapshot.approved[0].band).toBe('High');
 expect(externalRequests).toEqual([]);
});
