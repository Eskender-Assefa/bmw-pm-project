'use strict';
const $ = selector => document.querySelector(selector);
const escapeHtml = value => String(value ?? '').replace(/[&<>"']/g, char => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]));
const pct = value => value == null ? 'Unknown' : `${(value * 100).toFixed(1)}%`;
let ranking = null, selectedId = null, audit = null, loadingVersion = 0, busy = false;
const cohort = () => ({model: $('#model').value, country: $('#country').value, powertrain: $('#powertrain').value, origin: $('#origin').value});
const query = () => new URLSearchParams(cohort()).toString();
function notify(message, error = false) { $('#status').textContent = message; $('#status').classList.toggle('error', error); }
async function api(path, body) {
  const response = await fetch('/api/v1' + path, body === undefined ? {} : {method: 'POST', headers: {'Content-Type':'application/json'}, body: JSON.stringify(body)});
  const data = await response.json();
  if (!response.ok) throw Error(typeof data.detail === 'string' ? data.detail : JSON.stringify(data.detail || data));
  return data;
}
function visibleRows() {
  const term = $('#search').value.trim().toLowerCase();
  return (ranking?.requirements || []).filter(r => (!term || `${r.title} ${r.feature} ${r.category}`.toLowerCase().includes(term)) && ($('#band').value === 'all' || r.band === $('#band').value) && ($('#state').value === 'all' || r.status === $('#state').value));
}
function render() {
  const rows = visibleRows();
  if (!rows.some(r => r.id === selectedId)) selectedId = rows[0]?.id || null;
  $('#k-total').textContent = rows.length;
  $('#k-high').textContent = rows.filter(r => r.band === 'High').length;
  $('#k-approved').textContent = ranking?.requirements.filter(r => r.status === 'approved').length || 0;
  $('#k-evidence').textContent = ranking?.denominator ?? '—';
  $('#list-count').textContent = `${rows.length} requirements`;
  $('#requirements').innerHTML = rows.map(r => `<tr tabindex="0" role="button" aria-label="Review ${escapeHtml(r.title)}" aria-pressed="${r.id === selectedId}" class="problem-row ${r.id === selectedId ? 'selected' : ''}" data-id="${escapeHtml(r.id)}"><th>${escapeHtml(r.title)}<small>${escapeHtml(r.id)} · revision ${r.revision}${r.critical ? ' · Critical review' : ''}</small></th><td>${escapeHtml(r.feature)}<small>${escapeHtml(r.category)}</small></td><td><b>${pct(r.demand)}</b><small>${r.numerator} / ${r.denominator} records</small></td><td><span class="badge">${escapeHtml(r.band)}</span></td><td><span class="badge status-${escapeHtml(r.status)}">${escapeHtml(r.status)}</span></td></tr>`).join('') || '<tr><td colspan="5">No requirements match this cohort and these filters. Try another market or origin.</td></tr>';
  $('#requirements').querySelectorAll('[data-id]').forEach(row => {
    const choose = () => { selectedId = row.dataset.id; render(); };
    row.onclick = choose;
    row.onkeydown = event => { if (event.key === 'Enter' || event.key === ' ') { event.preventDefault(); choose(); } };
  });
  renderDetail();
}
function renderDetail() {
  const r = ranking?.requirements.find(r => r.id === selectedId);
  $('#decision-label').textContent = r ? `${r.category} · revision ${r.revision}` : '';
  if (!r) { $('#detail').textContent = 'No requirement selected.'; return; }
  $('#detail').innerHTML = `<h2>${escapeHtml(r.title)}</h2><div class="badges"><span class="badge status-${escapeHtml(r.status)}">${escapeHtml(r.status)}</span><span class="badge">${escapeHtml(r.band)} impact</span>${r.critical ? '<span class="badge status-challenged">Requires critical review</span>' : ''}</div><div class="reqtext">${escapeHtml(r.description)}</div><div class="scoregrid"><div class="scorecell"><small>Demand</small><strong>${pct(r.demand)}</strong></div><div class="scorecell"><small>Supporting records</small><strong>${r.numerator}</strong></div><div class="scorecell"><small>Eligible records</small><strong>${r.denominator}</strong></div><div class="scorecell"><small>Positive records</small><strong>${r.likes}</strong></div></div><h3>Acceptance criteria</h3><ul>${r.acceptance_criteria.map(c => `<li>${escapeHtml(c)}</li>`).join('')}</ul>${r.conflicts.length ? `<div class="uncertainty">${r.conflicts.map(escapeHtml).join('<br>')}</div>` : ''}<h3>Original feedback evidence</h3><p class="subtle">Up to eight examples; demand uses the full cohort. Generated by ${escapeHtml(r.generated_by)}.</p>${r.evidence_samples.map(e => `<details class="source"><summary>${escapeHtml(e.external_id)} · ${escapeHtml(e.country)} · ${escapeHtml(e.type)} · row ${escapeHtml(e.locator.row)}</summary><p>${escapeHtml(e.quote)}</p><button class="btn" data-evidence="${escapeHtml(e.id)}">View original source</button></details>`).join('')}<h3>PM decision</h3><div class="actions"><button class="btn good" data-action="approve">Approve</button><button class="btn" data-action="edit">Edit wording</button><button class="btn" data-action="postpone">Postpone</button><button class="btn danger" data-action="reject">Reject</button><button class="btn" data-action="set_band">Review impact</button><a class="btn" href="/cockpit">AI analysis &amp; full review tools</a></div>`;
  $('#detail').querySelectorAll('[data-action]').forEach(button => { button.disabled = busy; button.onclick = () => decide(button.dataset.action); });
  $('#detail').querySelectorAll('[data-evidence]').forEach(button => button.onclick = async () => {
    try {
      const e = await api('/evidence/' + encodeURIComponent(button.dataset.evidence));
      const url = `/api/v1/sources/${encodeURIComponent(e.source.id)}/file` + (e.locator.page ? `#page=${e.locator.page}` : '');
      const link = document.createElement('a'); link.href = url; link.target = '_blank'; link.rel = 'noopener'; link.textContent = `Open ${e.source.filename}`; link.className = 'btn'; button.replaceWith(link);
    } catch (error) { notify(error.message, true); }
  });
}
async function refresh() {
  const version = ++loadingVersion;
  ranking = null; render(); notify('Loading database…');
  try {
    const [data, history, sources, exports] = await Promise.all([api('/requirements?' + query()), api('/audit'), api('/sources'), api('/exports')]);
    if (version !== loadingVersion) return;
    ranking = data; audit = history;
    $('#sources').innerHTML = sources.map(s => `<a class="btn" target="_blank" rel="noopener" href="/api/v1/sources/${encodeURIComponent(s.id)}/file">${escapeHtml(s.filename)}</a>`).join('');
    $('#audit').innerHTML = `<p class="subtle">Integrity: ${history.integrity.valid ? 'verified' : 'check failed'}</p>` + history.events.map(e => `<div class="event"><time>${escapeHtml(new Date(e.timestamp).toLocaleString())}</time><strong>${escapeHtml(e.action)}</strong><p>${escapeHtml(e.actor)} · ${escapeHtml(e.entity_id)}${e.payload?.rationale ? '<br>' + escapeHtml(e.payload.rationale) : ''}</p></div>`).join('');
    $('#exports').innerHTML = exports.map(e => `<p><a href="/api/v1/exports/${encodeURIComponent(e.id)}/download">${escapeHtml(e.filename)}</a><br><small>${e.approved} approved requirements · ${escapeHtml(new Date(e.created_at).toLocaleString())}</small></p>`).join('') || '<p class="subtle">No exports yet. Export a board deck for this cohort.</p>';
    render(); notify(`${data.denominator.toLocaleString()} eligible records · ${data.requirements.length} requirements. Decisions save to the local database.`);
  } catch (error) { if (version === loadingVersion) notify(error.message, true); }
}
async function decide(action) {
  if (busy) return;
  const r = ranking?.requirements.find(r => r.id === selectedId);
  if (!r) return;
  const payload = {cohort: cohort(), expected_revision: r.revision, action, actor: 'Demo PM'};
  if (action === 'edit') {
    const title = prompt('Requirement title:', r.title); if (title === null) return;
    const description = prompt('Requirement description:', r.description); if (description === null) return;
    payload.title = title; payload.description = description;
  }
  if (action === 'set_band') {
    const band = prompt('Impact band: High, Medium, Low, or Unscored', r.band); if (band === null) return;
    if (!['High','Medium','Low','Unscored'].includes(band)) { notify('Choose High, Medium, Low, or Unscored.', true); return; }
    payload.band = band;
  }
  const rationale = prompt('Record the rationale for this decision:', ''); if (rationale === null) return;
  if (!rationale.trim()) { notify('Enter a rationale before saving the decision.', true); return; }
  payload.rationale = rationale;
  busy = true; renderDetail();
  try { await api(`/requirements/${encodeURIComponent(r.id)}/decisions`, payload); await refresh(); }
  catch (error) { notify(error.message, true); }
  finally { busy = false; renderDetail(); }
}
$('#export-audit').onclick = () => {
  if (!audit) return;
  const url = URL.createObjectURL(new Blob([JSON.stringify(audit, null, 2)], {type:'application/json'}));
  const link = document.createElement('a'); link.href = url; link.download = 'bmw-studio-audit.json'; link.click(); setTimeout(() => URL.revokeObjectURL(url), 1000);
};
$('#export-deck').onclick = async () => {
  const button = $('#export-deck'); button.disabled = true;
  try {
    let job = await api('/exports', {cohort: cohort(), include_scenario: true});
    notify('Generating board deck…');
    for (let count = 0; count < 120 && !['succeeded','failed','interrupted'].includes(job.state.toLowerCase()); count++) {
      await new Promise(resolve => setTimeout(resolve, 1000)); job = await api('/jobs/' + job.id);
    }
    if (job.state === 'succeeded') { await refresh(); notify('Board deck saved. Download it from Executive exports.'); }
    else throw Error(job.error || 'Export still running. Check Analysis & jobs in the full cockpit.');
  } catch (error) { notify(error.message, true); }
  finally { button.disabled = false; }
};
for (const selector of ['#model','#country','#powertrain','#origin']) $(selector).onchange = refresh;
for (const selector of ['#search','#band','#state']) $(selector).oninput = render;
$('#refresh').onclick = refresh;
(async () => {
  try {
    const meta = await api('/meta');
    $('#country').innerHTML = (meta.countries.length ? meta.countries : ['US']).map(c => `<option>${escapeHtml(c)}</option>`).join('');
    if (meta.countries.includes('US')) $('#country').value = 'US';
    await refresh();
  } catch (error) { notify(error.message, true); }
})();
